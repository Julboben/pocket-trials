// Builds TRAIL_AUTHORING_CONTEXT.md, a single file to hand to someone (or an
// AI) writing trails: the format spec, the validation code, the materials and
// example trails, copied from the files themselves so it never drifts.
// With --check it only reports whether the file is up to date.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const outputPath = join(root, 'TRAIL_AUTHORING_CONTEXT.md');

// An example trail's file, found by its id: the number in the file name moves
// when the career is reordered, the id doesn't.
const catalog = JSON.parse(readFileSync(join(root, 'trails/catalog.json'), 'utf8'));
const trailFile = id => {
  const entry = catalog.trails.find(item => item.id === id);
  if (!entry) throw new Error(`no trail ${id} in trails/catalog.json for the examples`);
  return 'trails/' + entry.file;
};

const SOURCES = [
  ['TRAIL_FORMAT.md', 'markdown', 'Trail format specification'],
  ['js/trail-schema.js', 'js', 'Schema, normalization and validation rules (the code is authoritative if it disagrees with the spec)'],
  ['js/materials.js', 'js', 'Valid terrain materials'],
  ['trails/custom/README.md', 'markdown', 'Where custom trail files go and how they are loaded'],
  [trailFile('official:the-orchard'), 'json', 'Example trail: easy'],
  [trailFile('official:kicker-canyon'), 'json', 'Example trail: medium'],
  [trailFile('official:long-way-up'), 'json', 'Example trail: advanced'],
  [trailFile('bonus:the-bonny-tyler'), 'json', 'Example trail: hard'],
];

const header = `# Hjulben: trail authoring context

This document gives you everything you need to create trails for Hjulben, a 2D side-scrolling bike trials game. It bundles the trail format spec, the validation code, the list of materials, and three official trails as examples.

<!-- Generated by scripts/generate-authoring-context.mjs; do not edit. Run \`npm run context\`. -->

## Your task

Create new trails as a single JSON file each, following the format below.

- Read the spec first, then check your output against \`validateTrail\` in \`js/trail-schema.js\`. If the spec and the code disagree, follow the code.
- Coordinates use the Canvas convention: \`x\` increases to the right and \`y\` increases **downward**, so a smaller \`y\` means higher terrain.
- Only use material names defined in \`js/materials.js\`.
- Output plain JSON (no comments, no trailing commas). The file will be saved in \`trails/custom/\`.
- Playtest as you build. If you can run commands in this repository, \`node scripts/playtest.mjs <trail file>\` solves the trail with the replay bot and reports every jump, turn, hang and crash, how forgiving each stretch is, and the bot's time; \`--probe\` measures a single jump or section, and \`--without\` checks that an apple really needs a skill (see "Playtesting from the command line" in the spec). Use it to design close to what the bike can do instead of guessing. If you can't run commands, keep gaps, slopes and jumps conservative (start gaps around 80–100 units wide) and treat medal times as rough estimates.

## Contents

${SOURCES.map(([path, , about], index) => `${index + 1}. \`${path}\`: ${about}`).join('\n')}
`;

// A fence longer than any run of backticks in the text, so embedded code
// blocks can't close it.
const fence = text => '`'.repeat(Math.max(3, ...[...text.matchAll(/`+/g)].map(match => match[0].length + 1)));

const sections = SOURCES.map(([path, language, about]) => {
  const text = readFileSync(join(root, path), 'utf8').replaceAll('\r\n', '\n').trimEnd();
  const marks = fence(text);
  return `## \`${path}\`\n\n${about}.\n\n${marks}${language}\n${text}\n${marks}\n`;
});

const output = [header, ...sections].join('\n---\n\n');
let current = '';
try { current = readFileSync(outputPath, 'utf8').replaceAll('\r\n', '\n'); } catch {}

if (current === output) console.log('TRAIL_AUTHORING_CONTEXT.md: up to date');
else if (process.argv.includes('--check')) {
  console.error('TRAIL_AUTHORING_CONTEXT.md: out of date. Run `npm run context` and commit the result.');
  process.exit(1);
} else {
  writeFileSync(outputPath, output);
  console.log('TRAIL_AUTHORING_CONTEXT.md: updated');
}
